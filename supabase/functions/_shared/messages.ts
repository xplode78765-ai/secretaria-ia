const CATALOG = { pt, es } as const;
export type MsgKey = keyof typeof pt;

export function msg(locale: Locale, key: MsgKey, vars: Record<string, string | number> = {}): string {
  const text = CATALOG[locale][key] ?? CATALOG.pt[key];
  return text.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}
